const getRadiant = (name: string): string | undefined =>
  radiantRules.find(({ match }) => name.includes(match))?.radiant;

export const METEOR_SHOWER_CATALOG: MeteorShowerCatalogEntry[] = showerNames.map((name) => {
  const radiant = getRadiant(name);
  if (!radiant) {
    throw new Error(`Missing radiant constellation for meteor shower: ${name}`);
  }
  return { name, radiant };
});
